-- SmartCare Dental schema for Supabase PostgreSQL.
-- Run in the Supabase SQL Editor before importing application data.

CREATE TABLE IF NOT EXISTS public.schema_migrations (
  id TEXT PRIMARY KEY,
  applied_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS public.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role TEXT NOT NULL CHECK (role IN ('patient', 'clerk', 'dentist', 'admin')),
  email TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  full_name TEXT NOT NULL,
  phone TEXT,
  is_demo INTEGER NOT NULL DEFAULT 0 CHECK (is_demo IN (0, 1)),
  active INTEGER NOT NULL DEFAULT 1,
  notification_opt_out INTEGER NOT NULL DEFAULT 0 CHECK (notification_opt_out IN (0, 1)),
  session_version INTEGER NOT NULL DEFAULT 1,
  face_descriptor TEXT,
  face_descriptor_consent_at TEXT,
  profile_image_type TEXT,
  profile_image_data BYTEA,
  profile_image_updated_at TEXT,
  consent_at TEXT,
  consent_policy_version TEXT,
  email_verified_at TEXT,
  created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE IF NOT EXISTS public.rate_limit_counters (
  scope_key TEXT PRIMARY KEY,
  failures INTEGER NOT NULL DEFAULT 0,
  reset_at BIGINT NOT NULL
);
